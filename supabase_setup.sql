create or replace function faxinas_private.cadastrar_perfil() returns trigger
language plpgsql security definer set search_path='' as $$
declare v_pessoa text; v_convite faxinas_private.convites; v_codigo text;
begin
 -- Outros aplicativos deste projeto não recebem um perfil de faxinas.
 if lower(new.email) not like '%@jessicmchdo.github.io' then return new; end if;
 select nome into v_pessoa from unnest(array['JUKEBOX','LOTERYA','KOMIXÃO','NAMOITA','NAZARÉ','CAMILA','BAQUETADA','AMANDA','BELA']) nome
 where faxinas_private.email_da_pessoa(nome)=lower(new.email);
 if v_pessoa is null or v_pessoa='NAMOITA' then raise exception 'Cadastro não autorizado.'; end if;
 v_codigo:=btrim(coalesce(new.raw_user_meta_data->>'codigo_liberacao',''));
 select * into v_convite from faxinas_private.convites where pessoa=v_pessoa for update;
 if not found or v_convite.usada_em is not null or v_convite.expira_em<=clock_timestamp()
    or v_codigo='' or v_convite.token_hash<>encode(sha256(convert_to(v_codigo,'UTF8')),'hex') then
   raise exception 'Código de liberação inválido ou vencido.';
 end if;
 insert into public.faxina_perfis(user_id,pessoa) values(new.id,v_pessoa);
 update faxinas_private.convites set usada_em=clock_timestamp() where pessoa=v_pessoa;
 return new;
end $$;
