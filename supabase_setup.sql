create or replace function faxinas_private.processar_vencidas(p_pessoa text default null) returns integer
language plpgsql security definer set search_path='' as $$
declare v_count integer;
begin
 update public.faxina_tarefas set estado='nao_concluida',multa_valor=30
 where encerra_em<=clock_timestamp() and estado<>'concluida' and (estado<>'nao_concluida' or multa_valor<>30)
 and (p_pessoa is null or pessoa=p_pessoa);
 get diagnostics v_count=row_count;return v_count;
end $$;
