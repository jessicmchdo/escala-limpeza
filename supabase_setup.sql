create or replace function faxinas_private.liberar_acesso(p_pessoa text) returns text
language plpgsql security definer set search_path='' as $$
declare v_token text;
begin
 if auth.uid() is null or faxinas_private.minha_pessoa() is distinct from 'NAMOITA' then raise exception 'Somente NAMOITA pode liberar acessos.'; end if;
 if p_pessoa not in ('JUKEBOX','LOTERYA','KOMIXÃO','NAZARÉ','CAMILA','BAQUETADA','AMANDA','BELA') or p_pessoa is null then raise exception 'Nome inválido.'; end if;
 if exists(select 1 from public.faxina_perfis where pessoa=p_pessoa) then raise exception 'Esta pessoa já cadastrou sua senha.'; end if;
 v_token:=replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');
 insert into faxinas_private.convites(pessoa,token_hash,expira_em,usada_em,liberada_por)
 values(p_pessoa,encode(sha256(convert_to(v_token,'UTF8')),'hex'),clock_timestamp()+interval '7 days',null,auth.uid())
 on conflict(pessoa) do update set token_hash=excluded.token_hash,expira_em=excluded.expira_em,usada_em=null,liberada_por=excluded.liberada_por;
 return v_token;
end $$;
