create or replace function faxinas_private.listar() returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_pessoa text;
begin
 v_pessoa:=faxinas_private.minha_pessoa();
 if auth.uid() is null or v_pessoa is null then raise exception 'Acesso não autorizado.'; end if;
 perform faxinas_private.processar_vencidas(case when v_pessoa='NAMOITA' then null else v_pessoa end);
 return coalesce((select jsonb_agg(jsonb_build_object(
 'id',id,'pessoa',pessoa,'semana',semana,'bloco',bloco,'tarefa',tarefa,'estado',estado,
 'estado_efetivo',case when encerra_em<=clock_timestamp() and estado<>'concluida' then 'nao_concluida' else estado end,
 'vencida',encerra_em<=clock_timestamp(),'prazo',encerra_em-interval '1 microsecond',
 'dia_vencimento',((encerra_em-interval '1 microsecond') at time zone 'America/Sao_Paulo')::date,
 'valor_multa',case when encerra_em<=clock_timestamp() and estado<>'concluida' then 30 else 0 end)
 order by semana desc,pessoa,bloco) from public.faxina_tarefas where pessoa=v_pessoa or v_pessoa='NAMOITA'),'[]'::jsonb);
end $$;
