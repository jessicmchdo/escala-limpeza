create table if not exists public.faxina_tarefas (
 id bigint generated by default as identity primary key,
 pessoa text not null check (pessoa in ('JUKEBOX','LOTERYA','KOMIXÃO','NAMOITA','NAZARÉ','CAMILA','BAQUETADA','AMANDA','BELA')),
 semana date not null check (semana >= date '2026-09-27' and extract(dow from semana)=0),
