create or replace function faxinas_private.marcar(p_id bigint,p_estado text) returns void
language plpgsql security definer set search_path='' as $$
declare v_pessoa text; v_tarefa public.faxina_tarefas; v_agora timestamptz;
begin
 v_pessoa:=faxinas_private.minha_pessoa();
 if auth.uid() is null or v_pessoa is null then raise exception 'Acesso não autorizado.'; end if;
 if p_estado is null or p_estado not in ('concluida','nao_concluida') then raise exception 'Estado inválido.'; end if;
 select * into v_tarefa from public.faxina_tarefas where id=p_id for update;
 if not found or (v_tarefa.pessoa<>v_pessoa and v_pessoa<>'NAMOITA') then raise exception 'Tarefa não autorizada.'; end if;
 v_agora:=clock_timestamp();
 if v_agora>=v_tarefa.encerra_em and v_pessoa<>'NAMOITA' then raise exception 'Prazo encerrado. Somente NAMOITA pode corrigir.'; end if;
 update public.faxina_tarefas set estado=p_estado,
 multa_valor=case when p_estado='nao_concluida' and v_agora>=encerra_em then 30 else 0 end,
 alterada_em=v_agora,alterada_por=auth.uid() where id=p_id;
 insert into faxinas_private.auditoria(tarefa_id,usuario_id,estado_anterior,estado_novo)
 values(p_id,auth.uid(),v_tarefa.estado,p_estado);
end $$;
