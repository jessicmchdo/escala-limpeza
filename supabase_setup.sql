create or replace function faxinas_private.sincronizar(p_escalas jsonb) returns integer
language plpgsql security definer set search_path='' as $$
declare s record; p record; b text; tarefa text; n integer:=0;
begin
 for s in select * from jsonb_each(p_escalas) loop
  if s.key::date<date '2026-09-27' then continue; end if;
  for p in select * from jsonb_each(s.value->'pessoas') loop
   foreach b in array array['dom_seg_ter','qui_sex_sab'] loop
    tarefa:=btrim(p.value->>b);
    if tarefa is null or tarefa='' or upper(tarefa) in ('FOLGA','AUSENTE') then
     delete from public.faxina_tarefas where semana=s.key::date and pessoa=p.key and bloco=b and encerra_em>clock_timestamp() and estado='pendente';
     continue;
    end if;
    insert into public.faxina_tarefas(pessoa,semana,bloco,tarefa,encerra_em)
    values(p.key,s.key::date,b,tarefa,(s.key::date::timestamp + case b when 'dom_seg_ter' then interval '3 days' else interval '7 days' end) at time zone 'America/Sao_Paulo')
    on conflict(semana,pessoa,bloco) do update set tarefa=excluded.tarefa
    where public.faxina_tarefas.encerra_em>clock_timestamp() and public.faxina_tarefas.estado='pendente';
    n:=n+1;
   end loop;
  end loop;
 end loop;
 return n;
end $$;
