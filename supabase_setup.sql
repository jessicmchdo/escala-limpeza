 tarefa text not null check (btrim(tarefa)<>'' and upper(btrim(tarefa)) not in ('FOLGA','AUSENTE')),
 encerra_em timestamptz not null,
 estado text not null default 'pendente' check (estado in ('pendente','concluida','nao_concluida')),
 multa_valor numeric(10,2) not null default 0 check (multa_valor in (0,30)),
 alterada_em timestamptz,
 alterada_por uuid references auth.users(id) on delete set null,
 unique(semana,pessoa,bloco)
);
